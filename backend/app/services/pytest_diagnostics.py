"""

pytest's default console output shows a mix of library frames (Selenium's
own call stack) and the uploaded test's frames, and when terminal output is
truncated to a tail it's easy to lose the uploaded test's own source line —
exactly the line engineers need to diagnose something like an
ElementClickInterceptedException. This module parses pytest's JUnit XML
report (generated by the pytest subprocess itself, never derived from or
written over an uploaded file) to extract, per failing test, the precise
frame that belongs to the uploaded test file rather than to a library or to
the execution engine's own generated conftest.py.

Pure parsing only — no execution, no side effects, no DB/schema changes.
"""

from __future__ import annotations

import re
import sys
from dataclasses import dataclass
from pathlib import Path
from xml.etree import ElementTree as ET


# A pytest traceback frame line usually looks like:
#   /tmp/run_39_xyz/test_corlink.py:45: in test_corlink_flow
# followed (on the next line) by the source line pytest echoes for that frame.
_FRAME_WITH_FUNC_RE = re.compile(r"^(?P<file>.+\.py):(?P<line>\d+): in (?P<func>.+)$")

# When the exception is raised directly in the test's own top-level frame
# (e.g. a bare `assert` at the top of the test body), pytest's rendered
# traceback has NO "in <func>" suffix at all for that frame — just
# "<file>:<line>:" followed by either nothing (blank trailing) or, for a
# library frame at the very bottom of the traceback, the raised exception's
# class name (e.g. "errorhandler.py:232: NoSuchElementException"). Both
# shapes are real frame locations and must be recognized as frames, not
# silently dropped.
_BARE_FRAME_RE = re.compile(r"^(?P<file>.+\.py):(?P<line>\d+):\s*(?P<rest>.*)$")

# pytest always prefixes the actual raised exception's summary line with
# "E" in its rendered traceback (e.g. "E   some.Exception: message"),
# regardless of how many stack frames came before it.
_EXCEPTION_SUMMARY_RE = re.compile(r"^E\s+(?P<summary>.+)$")

# A pytest "long" format source line that was elided/truncated, e.g. the
# assertion-introspection line pytest prefixes with ">" to show which
# expression actually failed.
_ASSERT_SOURCE_PREFIX_RE = re.compile(r"^>\s?(?P<source>.+)$")

# Library/engine-internal paths whose frames should never be reported as
# "the test's own line", even though they appear in the same traceback.
_NON_USER_PATH_MARKERS = ("site-packages", "dist-packages", "importlib", "selenium")
_NON_USER_FILENAMES = {"conftest.py"}

# Real Python installation directories (stdlib, venv standard library, the
# interpreter's own base install) — frames here are never the uploaded
# test's own code, even when nothing above matched by name.
_PYTHON_INSTALL_PREFIXES = tuple(
    str(Path(p).resolve()).replace("\\", "/")
    for p in {sys.prefix, getattr(sys, "base_prefix", sys.prefix)}
    if p
)


@dataclass(frozen=True)
class TracebackFrame:
    file: str
    line: int
    func: str
    source: str

    @property
    def is_user_frame(self) -> bool:
        normalized = self.file.replace("\\", "/")
        normalized_lower = normalized.lower()

        if Path(self.file).name in _NON_USER_FILENAMES:
            return False

        if any(marker in normalized_lower for marker in _NON_USER_PATH_MARKERS):
            return False

        try:
            resolved = str(Path(self.file).resolve()).replace("\\", "/")
        except OSError:
            resolved = normalized

        if any(resolved.startswith(prefix) for prefix in _PYTHON_INSTALL_PREFIXES if prefix):
            return False

        return True


@dataclass(frozen=True)
class TestFailureDiagnostic:
    """Everything needed to point an engineer at the exact failing step."""

    test_file: str
    test_class: str | None
    test_method: str
    source_line_number: int | None
    source_line: str | None
    exception_type: str | None
    exception_message: str | None

    def format(self) -> str:
        location = self.test_file
        if self.test_class:
            location = f"{location}::{self.test_class}::{self.test_method}"
        else:
            location = f"{location}::{self.test_method}"

        if self.source_line_number is not None:
            location = f"{location} (line {self.source_line_number})"

        lines = [f"FAILED {location}"]

        if self.source_line:
            lines.append(f"  source: {self.source_line}")

        if self.exception_type:
            lines.append(f"  exception: {self.exception_type}: {self.exception_message or ''}")

        return "\n".join(lines)


def parse_traceback_frames(traceback_text: str) -> list[TracebackFrame]:
    """Parses pytest's rendered traceback text into individual frames.

    pytest's "long" traceback format repeats, for every frame:
        <file>:<line>: in <function>
            <source line, indented>
    """

    lines = traceback_text.splitlines()
    frames: list[TracebackFrame] = []

    for i, line in enumerate(lines):
        stripped = line.strip()

        match = _FRAME_WITH_FUNC_RE.match(stripped)
        if match:
            source = lines[i + 1].strip() if i + 1 < len(lines) else ""
            frames.append(
                TracebackFrame(
                    file=match.group("file"),
                    line=int(match.group("line")),
                    func=match.group("func"),
                    source=source,
                )
            )
            continue

        # Bare "<file>:<line>:" form — no "in <func>" suffix. This is what
        # pytest emits for the top-level frame when the exception is raised
        # directly in the test's own body (e.g. a bare `assert`), and also
        # for the innermost library frame that actually raised the
        # exception. Either way it is a real frame location and must not be
        # silently dropped.
        bare_match = _BARE_FRAME_RE.match(stripped)
        if bare_match and not bare_match.group("rest").startswith("in "):
            func = bare_match.group("rest").strip()

            source = lines[i + 1].strip() if i + 1 < len(lines) else ""
            if not source or source.startswith("_") or source.startswith("E "):
                # No usable source line directly follows (blank line / the
                # "_ _ _" separator pytest prints before a truncated
                # section, or the exception summary). Look back for the
                # ">"-prefixed line pytest uses to mark the exact failing
                # expression, which is the real source for this frame.
                source = ""
                for prior in reversed(lines[:i]):
                    assert_match = _ASSERT_SOURCE_PREFIX_RE.match(prior.strip())
                    if assert_match:
                        source = assert_match.group("source").strip()
                        break
                    if prior.strip() and not prior.startswith((" ", "\t")):
                        # Walked past this frame's own source block without
                        # finding one.
                        break

            frames.append(
                TracebackFrame(
                    file=bare_match.group("file"),
                    line=int(bare_match.group("line")),
                    func=func,
                    source=source,
                )
            )

    return frames


def extract_exception_summary(traceback_text: str) -> tuple[str | None, str | None]:
    """Pulls the "ExceptionType: message" line out of a pytest traceback.

    pytest always prefixes the actual raised exception's summary with "E"
    (e.g. "E   some.Exception: message"), however many stack frames came
    before it, so that marker is the reliable signal — not position in the
    text. Falls back to the last non-frame line for tracebacks pytest
    didn't render in its usual long format."""

    for line in traceback_text.splitlines():
        match = _EXCEPTION_SUMMARY_RE.match(line.strip())

        if match:
            exc_type, _, exc_message = match.group("summary").partition(": ")
            return exc_type or None, exc_message or None

    for line in reversed(traceback_text.splitlines()):
        stripped = line.strip()

        if not stripped or line.startswith((" ", "\t")):
            continue

        if _FRAME_WITH_FUNC_RE.match(stripped) or _BARE_FRAME_RE.match(stripped):
            continue

        exc_type, _, exc_message = stripped.partition(": ")
        return exc_type or None, exc_message or None

    return None, None


def diagnose_failure(traceback_text: str) -> tuple[TracebackFrame | None, str | None, str | None]:
    """Given one failing test's full traceback text, returns the frame that
    belongs to the uploaded test itself (falling back to the last frame,
    then to a trailing file:line summary with no source, if nothing more
    specific is available), plus the exception type/message."""

    frames = parse_traceback_frames(traceback_text)
    user_frames = [f for f in frames if f.is_user_frame]
    frame = user_frames[-1] if user_frames else (frames[-1] if frames else None)

    if frame is None:
        for line in traceback_text.splitlines():
            match = _BARE_FRAME_RE.match(line.strip())
            if match:
                frame = TracebackFrame(file=match.group("file"), line=int(match.group("line")), func="", source="")

    exc_type, exc_message = extract_exception_summary(traceback_text)

    return frame, exc_type, exc_message


def parse_junit_report(junit_xml_path: Path) -> list[TestFailureDiagnostic]:
    """Parses a pytest-generated JUnit XML report and returns one
    TestFailureDiagnostic per failed/errored test case. Returns an empty
    list if the report is missing or has no failures (e.g. a crash before
    pytest could write it)."""

    if not junit_xml_path.exists():
        return []

    try:
        tree = ET.parse(junit_xml_path)
    except ET.ParseError:
        return []

    diagnostics: list[TestFailureDiagnostic] = []

    for testcase in tree.getroot().iter("testcase"):
        failure_node = testcase.find("failure")
        if failure_node is None:
            failure_node = testcase.find("error")
        if failure_node is None:
            continue

        classname = testcase.get("classname") or ""
        method = testcase.get("name") or "<unknown test>"

        # classname from pytest's junit report is "<module>" or
        # "<module>.<Class>" — split off a real test class if present.
        test_class = None
        if "." in classname:
            candidate = classname.rsplit(".", 1)[-1]
            if candidate and candidate[0].isupper():
                test_class = candidate

        traceback_text = failure_node.text or ""
        frame, exc_type, exc_message = diagnose_failure(traceback_text)

        # pytest's "file" testcase attribute isn't emitted by every
        # pytest/plugin version, so fall back to the file the traceback
        # itself points at (the most trustworthy source) before resorting
        # to a guess derived from the dotted classname. Only consider the
        # frame that is actually the uploaded test's own code — never a
        # Selenium/site-packages/stdlib frame — otherwise prefer the
        # classname-derived guess over a wrong library path.
        user_frame = frame if (frame is not None and frame.is_user_frame) else None
        test_file = testcase.get("file") or (user_frame.file if user_frame else None) or (
            classname.replace(".", "/") + ".py" if classname else "unknown.py"
        )
        # result_persistence_service.py's own JUnit testcase parsing always
        # reduces a derived file path down to its basename before using it
        # as the TestResult matching key (pytest/plugin versions embed full
        # run-temp-dir paths here, e.g. "/tmp/run_39_xyz/test_x.py", which
        # would never match). Mirror that exactly so diagnostics actually
        # join to the right TestResult row instead of being silently
        # dropped.
        test_file = Path(test_file).name

        diagnostics.append(
            TestFailureDiagnostic(
                test_file=test_file,
                test_class=test_class,
                test_method=method,
                source_line_number=frame.line if frame else None,
                source_line=frame.source if frame else None,
                exception_type=exc_type,
                exception_message=exc_message,
            )
        )

    return diagnostics
