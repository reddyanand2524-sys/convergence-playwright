def test_runtime_typed_value_is_masked_even_when_an_ide_comment_value_was_recorded(db_session, test_project, tmp_path):
    """The compat layer records the IDE comment's value in "value" when a comment
    matches; the value really typed (from a fixture) travels in "runtime_value".
    It must still be masked in failure text that has no secret-looking name."""
    from app.models.run_result import RunResult

    RUNTIME = "RUNTIME-FIXTURE-9z4k"
    make_project_file(db_session, test_project, "test_rt.py", "def test_a(): pass")
    run = make_run(db_session, test_project, status="RUNNING")
    trace = (
        "/tmp/run_1/test_rt.py:4: in test_a\n"
        ">       assert d.title == expected\n"
        f"E   AssertionError: assert 'spike' == '{RUNTIME}'\n"
        f"E     - {RUNTIME}\nE     + spike"
    )
    junit = tmp_path / "report.xml"
    junit.write_text(
        '<?xml version="1.0"?><testsuites><testsuite tests="1">'
        '<testcase classname="test_rt" name="test_a" time="1" file="test_rt.py">'
        f'<failure message="x">{escape(trace)}</failure></testcase></testsuite></testsuites>', encoding="utf-8")
    steps_path = tmp_path / "steps.json"
    steps_path.write_text(json.dumps([
        {"nodeid": "test_rt.py::test_a", "step": 2, "action": "type", "target": "id=field", "value": "from-ide-comment",
         "runtime_value": RUNTIME, "status": "PASS", "duration": 0.1, "error": "", "screenshot": "", "timestamp": 1700000000.0},
    ]), encoding="utf-8")

    persist_run_results(db_session, run, exit_code=1, stdout=f"assert 'spike' == '{RUNTIME}'", stderr="",
                        junit_report_path=junit, steps_json_path=steps_path, screenshots_dir=tmp_path / "screenshots")

    failure = db_session.scalar(select(FailureDiagnostic).join(TestResult).where(TestResult.run_id == run.id))
    out = db_session.scalar(select(RunResult.stdout).where(RunResult.run_id == run.id))
    stored = f"{failure.exception_message} {failure.raw_traceback} {out}"
    assert RUNTIME not in stored and "spike" in stored          # the typed value is masked, context kept
    step = db_session.scalar(select(StepResult).join(TestResult).where(TestResult.run_id == run.id))
    assert step.value == "***" and "runtime_value" not in step.__dict__    # never persisted


