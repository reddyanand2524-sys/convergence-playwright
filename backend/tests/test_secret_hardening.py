CODE_SECRET = "CODE-FIELD-77ef01"        # typed into id=code (nothing marks it secret)
FIXTURE_SECRET = "FIXTURE-DATA-ab12cd"   # from a data module: no literal on any secret-named line
STDOUT_MARKER = "STDOUT-ONLY-MARKER-91"  # harmless text that only exists in process output

DATA_DRIVEN_SCRIPT = '''from data import CREDS
class TestLogin():
  def test_otp(self):
    self.driver.find_element(By.ID, "code").send_keys(CREDS["otp"])
    self.driver.find_element(By.ID, "pin").send_keys(CREDS["pin"])
  def test_title(self):
    assert self.driver.title == "Welcome"
'''


def persist_data_driven_run(db_session, project, tmp_path):
    """A run whose typed values come from fixtures/data (no literal in the script)
    and whose failure output, traceback and stdout/stderr all repeat those values."""
    make_project_file(db_session, project, "test_otp.py", DATA_DRIVEN_SCRIPT)
    run = make_run(db_session, project, status="RUNNING", browser="chrome")
    trace_otp = (
        "/tmp/run_5/test_otp.py:4: in test_otp\n"
        f"    self.driver.find_element(By.ID, \"pin\").send_keys(CREDS[\"pin\"])\n"
        f"E   selenium.common.exceptions.InvalidElementStateException: Message: invalid element state value={CODE_SECRET} "
        f"for https://shop.test/verify?q=shoes&otp={FIXTURE_SECRET}\n"
        f"E   assert '{FIXTURE_SECRET}' == 'expected-value'"
    )
    trace_title = (
        "/tmp/run_5/test_otp.py:7: in test_title\n"
        ">       assert self.driver.title == \"Welcome\"\n"
        "E   AssertionError: assert 'Login' == 'Welcome'"
    )
    junit = tmp_path / "report.xml"
    junit.write_text(
        '<?xml version="1.0"?><testsuites><testsuite tests="2">'
        '<testcase classname="test_otp.TestLogin" name="test_otp" time="1" file="test_otp.py">'
        f'<failure message="x">{escape(trace_otp)}</failure></testcase>'
        '<testcase classname="test_otp.TestLogin" name="test_title" time="1" file="test_otp.py">'
        f'<failure message="x">{escape(trace_title)}</failure></testcase>'
        "</testsuite></testsuites>", encoding="utf-8")
    node = "test_otp.py::TestLogin::test_otp"
    events = [
        {"nodeid": node, "step": None, "action": "open", "target": "https://shop.test/verify?q=shoes", "value": "",
         "status": "PASS", "duration": 0.1, "error": "", "screenshot": "", "timestamp": 1700000000.0},
        {"nodeid": node, "step": None, "action": "type", "target": "tag:input", "value": CODE_SECRET, "status": "PASS",
         "duration": 0.1, "error": "", "screenshot": "", "timestamp": 1700000001.0},
        {"nodeid": node, "step": None, "action": "type", "target": "tag:input", "value": FIXTURE_SECRET, "status": "FAIL",
         "duration": 0.1, "error": f"InvalidElementStateException('value={FIXTURE_SECRET}')", "screenshot": "",
         "timestamp": 1700000002.0},
    ]
    steps_path = tmp_path / "steps.json"
    steps_path.write_text(json.dumps(events), encoding="utf-8")
    stdout = f"FAILED test_otp.py::TestLogin::test_otp - assert '{FIXTURE_SECRET}' == 'x'\n{STDOUT_MARKER}\n2 failed in 3.1s\n"
    stderr = f"WARNING typed {CODE_SECRET} into field\n"
    persist_run_results(db_session, run, exit_code=1, stdout=stdout, stderr=stderr, junit_report_path=junit,
                        steps_json_path=steps_path, screenshots_dir=tmp_path / "screenshots")
    run.status = "FAILED"
    db_session.commit()
    return run


FIXTURE_SECRETS = (CODE_SECRET, FIXTURE_SECRET)


def test_data_driven_secrets_are_not_stored(db_session, test_project, tmp_path):
    from app.models.run_result import RunResult

    run = persist_data_driven_run(db_session, test_project, tmp_path)

    steps = db_session.scalars(select(StepResult).join(TestResult).where(TestResult.run_id == run.id)).all()
    failures = db_session.scalars(select(FailureDiagnostic).join(TestResult).where(TestResult.run_id == run.id)).all()
    result = db_session.scalar(select(RunResult).where(RunResult.run_id == run.id))
    stored = " ".join(str(v) for row in steps for v in (row.target, row.value, row.error))
    stored += " ".join(str(v) for f in failures for v in (f.exception_type, f.exception_message, f.source_line, f.raw_traceback))
    stored += f" {result.stdout} {result.stderr}"
    for secret in FIXTURE_SECRETS:
        assert secret not in stored, secret
    # harmless context is preserved
    assert {s.action for s in steps} == {"open", "type"} and [s.value for s in steps if s.action == "type"] == ["***", "***"]
    assert STDOUT_MARKER in result.stdout and "2 failed" in result.stdout
    assert "/tmp/run_5" not in stored and "q=shoes" in stored and "Welcome" in stored


def test_data_driven_secrets_never_reach_api_or_reports(client, db_session, test_project, auth_headers, tmp_path):
    run = persist_data_driven_run(db_session, test_project, tmp_path)

    body = api_json(client, test_project, run, auth_headers)
    report = build_report_data(db_session, run, test_project)
    outputs = {
        "api": body,
        "html": render_html_report(report),
        "excel": excel_text(render_excel_report(report)),
        "pdf": pdf_text(render_pdf_report(report)),
    }

    for name, text in outputs.items():
        for secret in FIXTURE_SECRETS:
            assert secret not in text, f"{secret} leaked into {name}"
    # harmless, non-secret diagnostics stay readable everywhere
    import html as htmllib

    assert "'Login' == 'Welcome'" in outputs["api"] and "'Login' == 'Welcome'" in htmllib.unescape(outputs["html"])
    assert "q=shoes" in outputs["api"] and "Failure analysis" in outputs["pdf"]
    # raw process output is not returned by the API or any report
    assert STDOUT_MARKER not in " ".join(outputs.values()) and "stdout" not in json.loads(body)


def test_data_driven_secrets_in_old_rows_are_masked_on_read(client, db_session, test_project, auth_headers):
    """Historical rows keep raw typed values; reads must still mask them wherever
    they reappear (failure text, URLs, test ids), without rewriting the rows."""
