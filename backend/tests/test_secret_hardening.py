# Synthetic secrets (none of them look like real credentials).
TYPED = "TYPED-PW-7f3a"            # typed into a field whose locator names a password
KNOWN = "LITERAL-ZQ-91bc"          # a literal the script passes to a secret-named field
GENERIC = "GENERIC-FIELD-55de"     # typed into a field whose name says nothing (undetectable)
CRED = "urlpass-8c21"              # URL userinfo password
QTOKEN = "qtoken-44aa"             # sensitive query parameter
FRAG = "fragtoken-6b10"            # sensitive fragment parameter
SIG = "sig-value-93f2"             # signature parameter
ERR = "errsecret-1d9e"             # secret in an error message
KEEP_USER = "alice.smith"          # ordinary typed value that must survive
KEEP_QUERY = "q=running+shoes"     # ordinary URL parameter that must survive

URL_RAW = f"https://bob:{CRED}@shop.test/cb?token={QTOKEN}&{KEEP_QUERY}&sig={SIG}#access_token={FRAG}&view=full"

SCRIPT = f'''# Generated by Selenium IDE
class TestLogin():
  def test_login(self):
    # 1 | open | /login |
    self.driver.get("https://shop.test/login")
    # 2 | type | id=username | {KEEP_USER}
    self.driver.find_element(By.ID, "username").send_keys("{KEEP_USER}")
    # 3 | type | id=password | {TYPED}
    self.driver.find_element(By.ID, "password").send_keys("{TYPED}")
    self.driver.find_element(By.NAME, "user_pass").send_keys("{KNOWN}")
    self.driver.find_element(By.ID, "code").send_keys("{GENERIC}")
'''

SECRETS = (TYPED, KNOWN, CRED, QTOKEN, FRAG, SIG, ERR)


def pdf_text(pdf: bytes) -> str:
    """Decodes ReportLab's ASCII85+Flate page streams (no PDF library installed)."""
    chunks = []
    for raw in re.findall(rb"stream\r?\n(.*?)endstream", pdf, re.S):
        data = raw.strip()
        try:
            data = base64.a85decode(data[:-2] if data.endswith(b"~>") else data)
        except ValueError:
            pass
        try:
            data = zlib.decompress(data)
        except zlib.error:
            pass
        chunks.append(data.decode("latin-1", "ignore"))
    return "\n".join(chunks)


def excel_text(xlsx: bytes) -> str:
    wb = load_workbook(io.BytesIO(xlsx))
    return " ".join(str(c) for ws in wb for row in ws.iter_rows(values_only=True) for c in row if c is not None)


def seed_historical_run(db_session, project):
    """A finished run whose rows hold RAW secrets, as data stored before this
    hardening would."""
    make_project_file(db_session, project, "test_login.py", SCRIPT)
    run = make_run(db_session, project, status="FAILED", browser="chrome")
    run.completed_at = datetime(2026, 10, 9, 12, 0, 0)
    test = TestResult(run_id=run.id, nodeid="test_login.py::TestLogin::test_login", file_name="test_login.py",
                      class_name="TestLogin", method_name="test_login", status="FAILED", duration_seconds=2.0)
    db_session.add(test)
    db_session.commit()
    rows = [
        ("open", URL_RAW, "", "PASS", None),
        ("type", "id=username", KEEP_USER, "PASS", None),
        ("type", "id=password", TYPED, "PASS", None),                 # sensitive locator
        ("type", "input", KNOWN, "PASS", None),                        # tag-only target, literal known from the script
        ("type", "input", GENERIC, "PASS", None),                      # nothing identifies it as secret
        ("click", "id=go", "", "FAIL", f"NoSuchElementException(\"password={ERR}\")"),
    ]
    for i, (action, target, value, status, error) in enumerate(rows):
        db_session.add(StepResult(test_result_id=test.id, step_number=i + 1, action=action, target=target,
                                  value=value, status=status, error=error, sequence_index=i))
    db_session.add(FailureDiagnostic(
        test_result_id=test.id,
        exception_type="selenium.common.exceptions.NoSuchElementException",
        exception_message=f"Message: no such element password={ERR} at {URL_RAW}",
        source_line=f'self.driver.find_element(By.NAME, "user_pass").send_keys("{KNOWN}")',
        raw_traceback=(f">       self.driver.find_element(By.ID, \"password\").send_keys(\"{TYPED}\")\n"
                       f"E   AssertionError: assert '{TYPED}' == '{KNOWN}'\nE     - {KNOWN}\nE     + {TYPED}"),
    ))
    db_session.commit()
    return run, test


def api_json(client, project, run, headers) -> str:
    resp = client.get(f"/api/projects/{project.id}/runs/{run.id}/results", headers=headers)
    assert resp.status_code == 200
    return json.dumps(resp.json())


