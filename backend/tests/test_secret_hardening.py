def test_all_report_formats_are_free_of_secrets(db_session, test_project):
    run, _ = seed_historical_run(db_session, test_project)
    report = build_report_data(db_session, run, test_project)

    html = render_html_report(report)
    xlsx = excel_text(render_excel_report(report))
    pdf = pdf_text(render_pdf_report(report))

    assert "Failure analysis" in pdf            # positive control: the PDF decoder really sees the text
    for name, text in (("html", html), ("excel", xlsx), ("pdf", pdf)):
        for secret in SECRETS:
            assert secret not in text, f"{secret} leaked into the {name} report"
        assert KEEP_QUERY in text, f"harmless URL parameter missing from the {name} report"


def test_report_endpoints_serve_sanitized_output(client, db_session, test_project, auth_headers):
    run, _ = seed_historical_run(db_session, test_project)
    for kind, decode in (("html", lambda b: b.decode()), ("excel", excel_text), ("pdf", pdf_text)):
        resp = client.get(f"/api/projects/{test_project.id}/runs/{run.id}/report/{kind}", headers=auth_headers)
        assert resp.status_code == 200
        text = decode(resp.content)
        assert not any(secret in text for secret in SECRETS), kind


