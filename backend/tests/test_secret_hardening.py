def test_typed_value_is_masked_when_the_locator_names_a_secret():
    for target in ("id=password", "name=user_pass", "css=input[type=password]", "xpath=//input[@name='api_token']"):
        assert san.sanitize_step_value(target, TYPED) == "***"
    assert san.sanitize_step_value("id=username", KEEP_USER) == KEEP_USER      # ordinary value kept
    assert san.sanitize_step_value("id=passenger-name", "Alice") == "Alice"    # 'pass' inside a word


def test_known_literals_are_masked_even_when_the_target_is_only_a_tag_name():
    secrets = san.collect_known_secrets([SCRIPT])
    assert TYPED in secrets and KNOWN in secrets
    assert GENERIC not in secrets and KEEP_USER not in secrets   # not on secret-named lines
    assert san.sanitize_step_value("input", KNOWN, secrets) == "***"
    assert san.sanitize_step_value("input", f"prefix {KNOWN}", secrets) == "***"
    assert san.sanitize_step_value("input", KEEP_USER, secrets) == KEEP_USER


