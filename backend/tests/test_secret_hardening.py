def test_api_masks_secrets_in_historical_steps_failures_and_analysis(client, db_session, test_project, auth_headers):
    run, test = seed_historical_run(db_session, test_project)

    body = api_json(client, test_project, run, auth_headers)

    for secret in SECRETS:
        assert secret not in body, secret
    assert KEEP_QUERY in body and "id=username" in body                # harmless context survives
    assert KEEP_USER not in body                                        # typed values are not returned by default
    steps = {s["target"] + "|" + (s["value"] or ""): s for s in json.loads(body)["tests"][0]["steps"]}
    assert steps[f"id=password|***"]["action"] == "type"
    # stored history is untouched (sanitizing happens on output only)
    db_session.expire_all()
    stored = {s.target: s.value for s in db_session.scalars(select(StepResult).where(StepResult.test_result_id == test.id))}
    assert stored["id=password"] == TYPED
    assert TYPED in db_session.scalar(select(FailureDiagnostic.raw_traceback).where(FailureDiagnostic.test_result_id == test.id))


def test_value_typed_into_an_innocuous_field_is_not_returned(client, db_session, test_project, auth_headers):
    """Nothing identifies id=code or a bare <input> as secret, so typed values are
    not trusted by field name: they are never returned (the former known limit)."""
    run, _ = seed_historical_run(db_session, test_project)
    assert GENERIC not in api_json(client, test_project, run, auth_headers)


